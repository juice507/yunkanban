const { chromium } = require('playwright');
const path = require('path');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1536, height: 1050 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:4178/');
  await page.screenshot({path:path.join(__dirname,'preview-light.png'),fullPage:true});
  assert.equal(await page.locator('#rows tr').count(),8);
  await page.locator('#query').fill('林间');
  await page.locator('#search').click();
  assert.equal(await page.locator('#rows tr').count(),1);
  await page.locator('#rows [data-detail]').first().click();
  assert.equal(await page.locator('#overlay.open').count(),1);
  await page.keyboard.press('Escape');
  await page.locator('#reset').click();
  await page.locator('#allCheck').check();
  assert.equal(await page.locator('#selectedLabel').textContent(),'已选 8 项');
  await page.locator('#columns').click();
  await page.locator('[data-col="key"]').uncheck();
  assert.equal(await page.locator('th[data-column="key"]').isVisible(),false);
  await page.locator('[data-col="key"]').check();
  await page.locator('#columns').click();
  await page.locator('#allCheck').uncheck();
  await page.locator('#theme').click();
  assert.equal(await page.locator('body.dark').count(),1);
  await page.screenshot({path:path.join(__dirname,'preview-dark.png'),fullPage:true});
  await page.locator('#theme').click();
  await page.setViewportSize({width:800,height:1000});
  assert.equal(await page.locator('.sidebar').isVisible(),false);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('PASS: search, details, selection, columns, dark mode, responsive layout, no script errors');
})().catch(e=>{console.error(e);process.exitCode=1});
